# Build an Arch Linux .pkg.tar.zst from a Compose Desktop app-image.
# Pure shell implementation: no root, no makepkg, works on Arch/Ubuntu CI.
set -euo pipefail

APP_IMAGE="${1:?usage: build-arch.sh <app-image-dir> <output.pkg.tar.zst> <version> <repo-root>}"
OUTPUT="${2:?usage: build-arch.sh <app-image-dir> <output.pkg.tar.zst> <version> <repo-root>}"
VERSION="${3:?usage: build-arch.sh <app-image-dir> <output.pkg.tar.zst> <version> <repo-root>}"
REPO_ROOT="${4:?usage: build-arch.sh <app-image-dir> <output.pkg.tar.zst> <version> <repo-root>}"

[ -d "$APP_IMAGE" ] || { echo "missing app image: $APP_IMAGE" >&2; exit 1; }
for tool in tar zstd; do
  command -v "$tool" >/dev/null || { echo "missing tool: $tool (install zstd)" >&2; exit 1; }
done

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
PKG="$WORK/pkg"
mkdir -p "$PKG/usr/share/salt-player" "$PKG/usr/share/applications" \
         "$PKG/usr/share/icons/hicolor/512x512/apps" "$PKG/usr/bin"

cp -a "$APP_IMAGE/." "$PKG/usr/share/salt-player/"
cat > "$PKG/usr/bin/salt-player" <<'LAUNCH'
#!/usr/bin/env bash
exec /usr/share/salt-player/bin/salt-player "$@"
LAUNCH
chmod 755 "$PKG/usr/bin/salt-player"
cat > "$PKG/usr/share/applications/salt-player.desktop" <<'DESKTOP'
[Desktop Entry]
Type=Application
Version=1.0
Name=Salt Player
GenericName=Music Player
Comment=Salt Player (椒盐音乐) for Linux
Exec=/usr/bin/salt-player %F
Icon=salt-player
Terminal=false
Categories=AudioVideo;Audio;Player;
MimeType=audio/mpeg;audio/flac;audio/ogg;audio/opus;audio/x-wav;audio/mp4;
StartupNotify=true
DESKTOP
cp "$REPO_ROOT/icons/icon.png" "$PKG/usr/share/icons/hicolor/512x512/apps/salt-player.png"

# Standard Arch package metadata. pacman installs any archive containing .PKGINFO.
INSTALLED_SIZE=$(du -sk "$PKG" | cut -f1)
cat > "$PKG/.PKGINFO" <<PKGINFO
# Generated by Salt Player build script
pkgname = salt-player
pkgbase = salt-player
pkgver = $VERSION-1
pkgdesc = Salt Player (椒盐音乐) for Linux - tablet-style Compose desktop music player
url = https://github.com/ProgramerLiang/salt-player-for-linux
builddate = $(date +%s)
packager = Corripo <corripo@users.noreply.github.com>
size = $INSTALLED_SIZE
arch = x86_64
license = LGPL-3.0-or-later
depend = glibc
depend = gcc-libs
depend = gstreamer
depend = gst-plugins-base-libs
depend = hicolor-icon-theme
optdepend = gst-plugins-base: base audio decoders
optdepend = gst-plugins-good: mp3/ogg/flac decoders
optdepend = gst-plugins-bad: extra codecs
optdepend = gst-plugins-ugly: mp2/ape/aac decoders
optdepend = gst-libav: ffmpeg-based codecs
optdepend = mpv: libmpv playback backend
PKGINFO

# .BUILDINFO (optional but expected by pacman tooling).
cat > "$PKG/.BUILDINFO" <<BUILDINFO
format = 2
pkgver = $VERSION-1
pkgarch = x86_64
pkgbuild_sha256sum = none
packager = Corripo <corripo@users.noreply.github.com>
builddate = $(date +%s)
builddir = /build
startdir = /build
BUILDINFO

# .MTREE: minimal deterministic file list (one FILE entry per path).
{
  printf '#mtree\n'
  printf '. type=dir mode=0755 uid=0 gid=0 time=0\n'
  (cd "$PKG" && find . -mindepth 1 | LC_ALL=C sort | while read -r path; do
    rel="${path#./}"
    if [ -d "$PKG/$rel" ]; then
      printf '%s type=dir mode=0755 uid=0 gid=0 time=0\n' "$rel"
    else
      printf '%s type=file mode=0644 uid=0 gid=0 time=0 size=%s\n' "$rel" "$(stat -c%s "$PKG/$rel")"
    fi
  done)
} > "$PKG/.MTREE"

mkdir -p "$(dirname "$OUTPUT")"
rm -f "$OUTPUT" "$OUTPUT.tmp"

# Compress via a temporary tar file at a modest zstd level. This avoids a broken
# pipe silently truncating the archive if an earlier stage exits, and guarantees
# the completed archive is flushed before it is moved into place.
TAR_FILE="$WORK/salt-player.tar"
tar --format=gnu --owner=0 --group=0 --numeric-owner -cf "$TAR_FILE" -C "$PKG" .
zstd -3 -q -f -o "$OUTPUT.tmp" "$TAR_FILE"
[ -s "$OUTPUT.tmp" ] || { echo "compression produced an empty archive" >&2; exit 1; }
mv -f "$OUTPUT.tmp" "$OUTPUT"

# Self-check: complete zstd stream plus the entries pacman/desktop integration need.
zstd -t "$OUTPUT"
TARBALL_LIST="$WORK/archive-list.txt"
tar --use-compress-program=zstd -tf "$OUTPUT" > "$TARBALL_LIST"
for required in \
  ./.PKGINFO \
  ./.BUILDINFO \
  ./.MTREE \
  ./usr/bin/salt-player \
  ./usr/share/applications/salt-player.desktop; do
  if ! grep -Fxq "$required" "$TARBALL_LIST"; then
    echo "archive is missing required entry: $required" >&2
    exit 1
  fi
done

echo "wrote $OUTPUT ($(stat -c%s "$OUTPUT") bytes)"
