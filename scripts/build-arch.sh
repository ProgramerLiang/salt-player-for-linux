# Build an Arch Linux .pkg.tar.zst from a Compose Desktop app-image.
# Pure shell implementation: no root, no makepkg, works on Arch/Ubuntu CI.
set -euo pipefail

APP_IMAGE="${1:?usage: build-arch.sh <app-image-dir> <output.pkg.tar.zst> <version> <repo-root>}"
OUTPUT="${2:?usage: build-arch.sh <app-image-dir> <output.pkg.tar.zst> <version> <repo-root>}"
VERSION="${3:?usage: build-arch.sh <app-image-dir> <output.pkg.tar.zst> <version> <repo-root>}"
REPO_ROOT="${4:?usage: build-arch.sh <app-image-dir> <output.pkg.tar.zst> <version> <repo-root>}"

[ -d "$APP_IMAGE" ] || { echo "missing app image: $APP_IMAGE" >&2; exit 1; }
for tool in tar zstd; do
  command -v "$tool" >/dev/null || { echo "missing tool: $tool (install zstd)" >&2; exit 1; }
done

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
PKG="$WORK/pkg"
mkdir -p "$PKG/usr/share/salt-shaker" "$PKG/usr/share/applications" "$PKG/usr/bin"

cp -a "$APP_IMAGE/." "$PKG/usr/share/salt-shaker/"
cat > "$PKG/usr/bin/salt-shaker" <<'LAUNCH'
#!/usr/bin/env bash
exec /usr/share/salt-shaker/bin/salt-shaker "$@"
LAUNCH
chmod 755 "$PKG/usr/bin/salt-shaker"
cat > "$PKG/usr/share/applications/salt-shaker.desktop" <<'DESKTOP'
[Desktop Entry]
Type=Application
Version=1.0
Name=椒盐罐
Name[en]=Salt Shaker
GenericName=Music Player
Comment=椒盐音乐（Salt Player）的 Linux 社区衍生版
Exec=/usr/bin/salt-shaker %F
Icon=salt-shaker
Terminal=false
Categories=AudioVideo;Audio;Player;
MimeType=audio/mpeg;audio/flac;audio/ogg;audio/opus;audio/x-wav;audio/mp4;
StartupNotify=true
StartupWMClass=com-saltplayer-MainKt
DESKTOP
# Install every hicolor size plus the scalable source so the launcher, dock and switcher
# each pick a crisp bitmap instead of downscaling a single 512px file.
for size in 16 24 32 48 64 128 256 512; do
  install -Dm644 "$REPO_ROOT/icons/hicolor/${size}x${size}/apps/salt-shaker.png" \
    "$PKG/usr/share/icons/hicolor/${size}x${size}/apps/salt-shaker.png"
done
install -Dm644 "$REPO_ROOT/icons/salt-shaker.svg" \
  "$PKG/usr/share/icons/hicolor/scalable/apps/salt-shaker.svg"

# Post-install scriptlet: refresh the icon cache and desktop database so the launcher shows
# the application icon immediately after installation instead of after the next login.
cat > "$PKG/.INSTALL" <<'INSTALL'
post_install() {
  gtk-update-icon-cache -q -t -f /usr/share/icons/hicolor 2>/dev/null || true
  update-desktop-database -q /usr/share/applications 2>/dev/null || true
}
post_upgrade() {
  post_install
}
post_remove() {
  gtk-update-icon-cache -q -t -f /usr/share/icons/hicolor 2>/dev/null || true
  update-desktop-database -q /usr/share/applications 2>/dev/null || true
}
INSTALL

# Standard Arch package metadata. pacman installs any archive containing .PKGINFO.
INSTALLED_SIZE=$(du -sk "$PKG" | cut -f1)
cat > "$PKG/.PKGINFO" <<PKGINFO
# Generated by Salt Player build script
pkgname = salt-shaker
pkgbase = salt-shaker
pkgver = $VERSION-1
pkgdesc = Salt Shaker - community Linux port of Salt Player (椒盐音乐)
url = https://github.com/ProgramerLiang/salt-shaker
builddate = $(date +%s)
packager = Corripo <corripo@users.noreply.github.com>
size = $INSTALLED_SIZE
arch = x86_64
license = LGPL-3.0-or-later
depend = glibc
depend = gcc-libs
depend = gstreamer
depend = gst-plugins-base-libs
depend = hicolor-icon-theme
optdepend = gst-plugins-base: base audio decoders
optdepend = gst-plugins-good: mp3/ogg/flac decoders
optdepend = gst-plugins-bad: extra codecs
optdepend = gst-plugins-ugly: mp2/ape/aac decoders
optdepend = gst-libav: ffmpeg-based codecs
optdepend = mpv: libmpv playback backend
PKGINFO

# .BUILDINFO (optional but expected by pacman tooling).
cat > "$PKG/.BUILDINFO" <<BUILDINFO
format = 2
pkgver = $VERSION-1
pkgarch = x86_64
pkgbuild_sha256sum = none
packager = Corripo <corripo@users.noreply.github.com>
builddate = $(date +%s)
builddir = /build
startdir = /build
BUILDINFO


mkdir -p "$(dirname "$OUTPUT")"
rm -f "$OUTPUT" "$OUTPUT.tmp"

# pacman requires metadata files at the archive root WITHOUT a leading "./".
# Building the tar from an explicit sorted file list avoids GNU tar's synthetic "." entry.
TAR_FILE="$WORK/salt-player.tar"
(
  cd "$PKG"
  find . -mindepth 1 -printf '%P\n' | LC_ALL=C sort > "$WORK/archive-files-sorted.txt"
  {
    echo '.PKGINFO'
    grep -Fxv '.PKGINFO' "$WORK/archive-files-sorted.txt"
  } > "$WORK/archive-files.txt"
  # -T lists both directories and their children; without --no-recursion GNU tar
  # re-adds each child while expanding the directory, producing duplicate
  # self-referential hardlink entries that pacman skips on extraction.
  tar --format=gnu --owner=0 --group=0 --numeric-owner --no-recursion -cf "$TAR_FILE" -T "$WORK/archive-files.txt"
)
zstd -3 -q -f -o "$OUTPUT.tmp" "$TAR_FILE"
[ -s "$OUTPUT.tmp" ] || { echo "compression produced an empty archive" >&2; exit 1; }
mv -f "$OUTPUT.tmp" "$OUTPUT"

# Strict self-check: exact root metadata names, no "./" entries at all.
zstd -t "$OUTPUT"
TARBALL_LIST="$WORK/archive-list.txt"
tar --use-compress-program=zstd -tf "$OUTPUT" > "$TARBALL_LIST"
FIRST_ENTRY="$(head -n 1 "$TARBALL_LIST")"
[ "$FIRST_ENTRY" = ".PKGINFO" ] || {
  echo "first archive entry must be .PKGINFO, got: $FIRST_ENTRY" >&2
  exit 1
}
for required in \
  '.PKGINFO' \
  '.BUILDINFO' \
  'usr/bin/salt-shaker' \
  'usr/share/applications/salt-shaker.desktop'; do
  grep -Fxq "$required" "$TARBALL_LIST" || {
    echo "archive is missing required entry: $required" >&2
    exit 1
  }
done
if grep -Eq '^\./' "$TARBALL_LIST"; then
  echo "archive contains invalid ./-prefixed entries" >&2
  grep -E '^\./' "$TARBALL_LIST" | head -5 >&2
  exit 1
fi
# Duplicate entries make GNU tar emit self-referential hardlink records that
# pacman silently skips, so reject them explicitly.
DUPLICATES="$(sort "$TARBALL_LIST" | uniq -d)"
if [ -n "$DUPLICATES" ]; then
  echo "archive contains duplicate entries (bad for pacman):" >&2
  echo "$DUPLICATES" | head -10 >&2
  exit 1
fi


# Unpack the finished archive and verify that the payload files are regular,
# non-empty files (this catches broken hardlink/metadata generation).
EXTRACT_DIR="$WORK/extract"
mkdir -p "$EXTRACT_DIR"
tar --use-compress-program=zstd -xf "$OUTPUT" -C "$EXTRACT_DIR"
for payload in \
  'usr/bin/salt-shaker' \
  'usr/share/applications/salt-shaker.desktop' \
  'usr/share/salt-shaker/bin/salt-shaker'; do
  target="$EXTRACT_DIR/$payload"
  [ -f "$target" ] || { echo "unpacked payload is not a regular file: $payload" >&2; exit 1; }
  [ -s "$target" ] || { echo "unpacked payload is empty: $payload" >&2; exit 1; }
  echo "verified unpacked file: $payload ($(stat -c%s "$target") bytes)"
done

echo "wrote $OUTPUT ($(stat -c%s "$OUTPUT") bytes)"
